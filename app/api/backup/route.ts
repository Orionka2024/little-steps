import { getCurrentUser } from '../../../lib/auth-server';
import { getStoredRecords, upsertStoredRecords, deleteStoredRecord } from '../../../lib/storage';
import { EntryPayloadSchema, type ValidatedEntry } from '../../../lib/validation';
import type { Entry } from '../../../lib/types';
import { isAssignment, isMaterial, isAttendance, isSubmission, isMessage } from '../../../lib/types';

export async function GET(req: Request) {
  const user = await getCurrentUser();
  if (!user) {
    return Response.json(
      { error: 'Please sign in to access curriculum backups.' },
      { status: 401 }
    );
  }

  const records = await getStoredRecords('local_seedy');
  const entries = records as unknown as Entry[];

  // If student, filter out unposted items
  const filtered = user.role === 'Student'
    ? entries.filter((e) => {
        if (e.kind === 'assignment') {
          return (e as { posted?: boolean }).posted !== false;
        }
        return true;
      })
    : entries;

  const stats = {
    assignmentsCount: filtered.filter(isAssignment).length,
    materialsCount: filtered.filter(isMaterial).length,
    attendanceCount: filtered.filter(isAttendance).length,
    submissionsCount: filtered.filter(isSubmission).length,
    messagesCount: filtered.filter(isMessage).length,
    totalEntries: filtered.length,
  };

  const timestamp = new Date().toISOString();
  const backupBundle = {
    version: '1.0',
    app: 'little-steps',
    timestamp,
    source: 'server',
    description: `Curriculum export generated by ${user.role} (${user.displayName || user.username})`,
    stats,
    entries: filtered,
  };

  const url = new URL(req.url);
  const isDownload = url.searchParams.get('download') === '1' || url.searchParams.get('download') === 'true';

  if (isDownload) {
    const dateStr = timestamp.split('T')[0];
    return new Response(JSON.stringify(backupBundle, null, 2), {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        'Content-Disposition': `attachment; filename="little-steps-curriculum-backup-${dateStr}.json"`,
      },
    });
  }

  return Response.json(backupBundle);
}

export async function POST(req: Request) {
  const user = await getCurrentUser();
  if (!user) {
    return Response.json(
      { error: 'Please sign in first.' },
      { status: 401 }
    );
  }

  if (user.role !== 'Teacher') {
    return Response.json(
      { error: 'Only teachers can restore curriculum backups.' },
      { status: 403 }
    );
  }

  const bodyText = await req.text();
  if (bodyText.length > 2000000) {
    return Response.json(
      { error: 'Backup payload is too large (max 2 MB).' },
      { status: 413 }
    );
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(bodyText);
  } catch {
    return Response.json({ error: 'Invalid JSON payload.' }, { status: 400 });
  }

  let itemsToValidate: unknown[] = [];
  if (parsed && typeof parsed === 'object') {
    if (Array.isArray((parsed as { entries?: unknown[] }).entries)) {
      itemsToValidate = (parsed as { entries: unknown[] }).entries;
    } else if (Array.isArray(parsed)) {
      itemsToValidate = parsed as unknown[];
    } else {
      return Response.json(
        { error: 'Backup must contain an array of entries or an entries field.' },
        { status: 400 }
      );
    }
  }

  const validatedList: ValidatedEntry[] = [];
  for (let i = 0; i < itemsToValidate.length; i++) {
    const item = itemsToValidate[i];
    const parseResult = EntryPayloadSchema.safeParse(item);
    if (!parseResult.success) {
      const errorDetails = parseResult.error.errors.map((e) => e.message).join(', ');
      return Response.json(
        { error: `Validation error at entry ${i}: ${errorDetails}` },
        { status: 400 }
      );
    }
    validatedList.push(parseResult.data);
  }

  // Clear deletion tombstones if an attendance record is being restored
  for (const item of validatedList) {
    if (item.kind === 'attendance') {
      await deleteStoredRecord(`del_${item.id}`, 'local_seedy');
      if (item.date) {
        await deleteStoredRecord(`del_att-${item.date}`, 'local_seedy');
      }
    }
  }

  if (validatedList.length > 0) {
    await upsertStoredRecords(
      validatedList.map((item) => ({
        id: item.id,
        owner: 'local_seedy',
        kind: item.kind,
        data: item as unknown as Record<string, unknown>,
      }))
    );
  }

  const entries = validatedList as unknown as Entry[];
  const stats = {
    assignmentsCount: entries.filter(isAssignment).length,
    materialsCount: entries.filter(isMaterial).length,
    attendanceCount: entries.filter(isAttendance).length,
    submissionsCount: entries.filter(isSubmission).length,
    messagesCount: entries.filter(isMessage).length,
    totalEntries: entries.length,
  };

  return Response.json({
    ok: true,
    restoredCount: validatedList.length,
    stats,
  });
}
